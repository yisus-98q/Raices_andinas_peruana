// Se recorre forma por forma en vez de insumo por insumo: así el catálogo
// queda repartido entre categorías aunque se corte antes de llegar al final.
const catalogoFormas = new Map(INSUMOS.map((i) => [i.n, formasDe(i)]));
const maxFormas = Math.max(...[...catalogoFormas.values()].map((f) => f.length));
for (let vuelta = 0; vuelta < maxFormas && productos.length < OBJETIVO; vuelta++) {
  for (const ins of INSUMOS) {
    if (productos.length >= OBJETIVO) break;
    const forma = catalogoFormas.get(ins.n)[vuelta];
    if (!forma) continue;

    const f = FORMAS[forma];
    if (!f) { console.warn('Forma sin definir: ' + forma); continue; }

    const nombre = (ins.n + ' ' + f.sufijo).replace(/\s+/g, ' ').trim();
    if (usados.has(nombre)) continue;
    usados.add(nombre);

    // Precio con una variación pequeña, para que no parezca una tabla.
    const precio = Math.round(ins.base * f.mult * (0.94 + aleatorio() * 0.12) * 2) / 2 - 0.10;
    const margen = 0.42 + aleatorio() * 0.16;          // 42 % a 58 %
    // El stock no se reparte plano entre 0 y 60. Con eso, uno de cada seis
    // productos quedaba en o por debajo de su minimo y el panel abria con 66
    // alertas de reposicion: un muro que no dice nada y en el que el dueno no
    // encuentra lo que de verdad tiene que comprar. Un almacen real tiene casi
    // todo surtido, unos pocos por reponer y algun agotado — que es lo que hace
    // que el bloque de reposicion signifique algo, y lo que deja ver el
    // "Agotado" en la tienda sin llenarla de huecos.
    const stockMin = entre(5, 15);
    const suerte = aleatorio();
    const stock =
      suerte < 0.015 ? 0                       // agotado, 1,5 %
        : suerte < 0.04 ? entre(1, stockMin)   // por reponer, 2,5 %
          : entre(stockMin + 5, 60);           // surtido, el resto

    const sigla = SIGLA[ins.cat] || 'GEN';
    const numero = String(productos.filter((p) => p.sku.startsWith(sigla)).length + 1)
      .padStart(3, '0');

    productos.push({
      sku: `${sigla}-${numero}`,
      nombre,
      categoria: ins.cat,
      origen: ins.origen,
      presentacion: f.pres,
      descripcion: `${ins.ben}. ${ins.n} de ${ins.origen}, en ${f.pres.toLowerCase()}.`,
      uso_tradicional: ins.uso,
      beneficios: ins.ben,
      etiquetas: sinTildes(ins.tags),
      precio: Math.max(4.9, Math.round(precio * 10) / 10),
      costo: Math.round(precio * (1 - margen) * 10) / 10,
      stock,
      stock_min: stockMin,
      emoji: '',
    });
  }
}

